package surface

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strings"

	"gopkg.in/yaml.v3"

	"gitlab.com/gorib/waffle/internal/gomod"
)

// Version is the format this waffle writes and the newest it reads.
const Version = 1

// File is where a service keeps its record, from the module root.
var File = filepath.Join("tests", "surface.yaml")

type Surface struct {
	Version   int      `yaml:"version"`
	Service   string   `yaml:"service"`
	Publishes []string `yaml:"publishes,omitempty"`
	Consumes  []string `yaml:"consumes,omitempty"`
	Serves    []string `yaml:"serves,omitempty"`
	Calls     []string `yaml:"calls,omitempty"`
	Clients map[string][]string `yaml:"clients,omitempty"`
	// Calls between the module's own domains: a modular monolith's links.
	Domains []string `yaml:"domains,omitempty"`
	// From the service's waffle.yaml, not its code.
	Hosts map[string]string `yaml:"-"`
}

const header = "# Generated by `waffle flows record`; the service's tests fail when it falls behind the code.\n"

func (s Surface) Encode() []byte {
	var b bytes.Buffer
	b.WriteString(header)
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	_ = enc.Encode(s)
	return b.Bytes()
}

func Read(file string) (Surface, error) {
	body, err := os.ReadFile(file)
	if err != nil {
		return Surface{}, err
	}
	var s Surface
	if err := yaml.Unmarshal(body, &s); err != nil {
		return Surface{}, fmt.Errorf("%s: %w", file, err)
	}
	switch {
	case s.Version == 0:
		return Surface{}, fmt.Errorf("%s: no version", file)
	case s.Version > Version:
		return Surface{}, fmt.Errorf("%s: version %d is newer than this waffle reads (%d)", file, s.Version, Version)
	case s.Service == "":
		return Surface{}, fmt.Errorf("%s: no service", file)
	}
	return s, nil
}

// Check fails when the module's record no longer matches its code.
func Check() error {
	root, err := gomod.Root()
	if err != nil {
		return err
	}
	fresh, err := Extract(root)
	if err != nil {
		return err
	}
	current, err := os.ReadFile(filepath.Join(root, File))
	if errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("%s is missing — run `./waffle flows record` and commit it", File)
	}
	if err != nil {
		return err
	}
	if bytes.Equal(current, fresh.Encode()) {
		return nil
	}
	var old Surface
	_ = yaml.Unmarshal(current, &old)
	return fmt.Errorf("%s does not match the code — run `./waffle flows record` and review the diff:\n%s", File, diff(old, fresh))
}

func diff(old, fresh Surface) string {
	var b strings.Builder
	section := func(name string, was, now []string) {
		for _, x := range now {
			if !slices.Contains(was, x) {
				fmt.Fprintf(&b, "  + %s %s\n", name, x)
			}
		}
		for _, x := range was {
			if !slices.Contains(now, x) {
				fmt.Fprintf(&b, "  - %s %s\n", name, x)
			}
		}
	}
	section("publishes", old.Publishes, fresh.Publishes)
	section("consumes", old.Consumes, fresh.Consumes)
	section("serves", old.Serves, fresh.Serves)
	section("calls", old.Calls, fresh.Calls)
	section("clients", byClient(old.Clients), byClient(fresh.Clients))
	section("domains", old.Domains, fresh.Domains)
	if b.Len() == 0 {
		b.WriteString("  (only the layout differs)\n")
	}
	return b.String()
}

func byClient(clients map[string][]string) []string {
	var out []string
	for _, client := range sorted(clients) {
		for _, m := range clients[client] {
			out = append(out, client+": "+m)
		}
	}
	return out
}

func service(module string) string { return path.Base(module) }
